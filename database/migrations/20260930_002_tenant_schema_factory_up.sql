-- Copilot Protheus
-- Migration 20260930_002 UP
-- Instala factory idempotente para schemas físicos por tenant.
-- Não replica tabelas transacionais do ERP.

BEGIN;

CREATE OR REPLACE FUNCTION public.provision_tenant_schema(p_tenant_code varchar)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $factory$
DECLARE
    v_schema text;
BEGIN
    SELECT schema_name
      INTO v_schema
      FROM public.tenant
     WHERE tenant_code = p_tenant_code
       AND status IS DISTINCT FROM 'DECOMMISSIONED';

    IF v_schema IS NULL THEN
        RAISE EXCEPTION 'Tenant inexistente/inativo ou schema_name não configurado: %', p_tenant_code;
    END IF;

    IF v_schema !~ '^[a-z][a-z0-9_]{2,62}$' THEN
        RAISE EXCEPTION 'schema_name inválido: %', v_schema;
    END IF;

    IF v_schema IN ('public', 'pg_catalog', 'information_schema') OR v_schema LIKE 'pg_%' THEN
        RAISE EXCEPTION 'schema_name reservado: %', v_schema;
    END IF;

    EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I', v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.tenant_modules (
            module_id integer PRIMARY KEY
                REFERENCES public.protheus_modules_master(id)
                ON UPDATE RESTRICT ON DELETE RESTRICT,
            enabled boolean NOT NULL DEFAULT true,
            provisioned_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.dictionary_tables (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_id integer,
            table_code varchar(32) NOT NULL,
            table_name varchar(128) NOT NULL,
            physical_name varchar(128) NOT NULL,
            module_id integer NOT NULL
                REFERENCES public.protheus_modules_master(id),
            description text,
            active boolean NOT NULL DEFAULT true,
            metadata_json jsonb NOT NULL DEFAULT '{}'::jsonb,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE NULLS NOT DISTINCT (company_id, physical_name)
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.dictionary_fields (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            dictionary_table_id bigint NOT NULL
                REFERENCES %I.dictionary_tables(id) ON DELETE CASCADE,
            field_name varchar(128) NOT NULL,
            title varchar(255),
            field_type varchar(64) NOT NULL,
            length_num integer,
            decimal_num integer,
            required boolean NOT NULL DEFAULT false,
            browsable boolean NOT NULL DEFAULT true,
            virtual boolean NOT NULL DEFAULT false,
            validation_rule text,
            semantic_json jsonb NOT NULL DEFAULT '{}'::jsonb,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (dictionary_table_id, field_name)
        )
    $ddl$, v_schema, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.dictionary_indexes (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            dictionary_table_id bigint NOT NULL
                REFERENCES %I.dictionary_tables(id) ON DELETE CASCADE,
            index_order integer NOT NULL,
            nickname varchar(128),
            expression text NOT NULL,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (dictionary_table_id, index_order)
        )
    $ddl$, v_schema, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.business_rules (
            id uuid PRIMARY KEY,
            company_id integer,
            module_id integer REFERENCES public.protheus_modules_master(id),
            intent_code varchar(100),
            rule_type varchar(100) NOT NULL,
            rule_name varchar(255) NOT NULL,
            rule_json jsonb NOT NULL,
            version integer NOT NULL DEFAULT 1 CHECK (version > 0),
            active boolean NOT NULL DEFAULT true,
            created_by uuid,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE NULLS NOT DISTINCT (company_id, rule_type, rule_name, version)
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.documents (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            visibility varchar(32) NOT NULL DEFAULT 'TENANT',
            title varchar(255) NOT NULL,
            source_path text,
            source_type varchar(64),
            module_id integer REFERENCES public.protheus_modules_master(id),
            category varchar(100),
            version varchar(64),
            status varchar(32) NOT NULL DEFAULT 'ACTIVE',
            checksum varchar(128),
            language varchar(16),
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.document_chunks (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            document_id bigint NOT NULL REFERENCES %I.documents(id) ON DELETE CASCADE,
            chunk_order integer NOT NULL,
            content text NOT NULL,
            token_count integer,
            embedding_model varchar(100),
            vector vector,
            page_number integer,
            section varchar(255),
            created_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (document_id, chunk_order)
        )
    $ddl$, v_schema, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.memories (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_id integer,
            visibility varchar(32) NOT NULL DEFAULT 'TENANT',
            memory_key varchar(255) NOT NULL,
            memory_value text NOT NULL,
            memory_type varchar(64),
            scope varchar(64),
            tags jsonb NOT NULL DEFAULT '[]'::jsonb,
            confidence integer CHECK (confidence BETWEEN 0 AND 100),
            source varchar(255),
            expires_at timestamptz,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.conversations (
            id uuid PRIMARY KEY,
            user_id uuid NOT NULL,
            title varchar(255),
            domain_code varchar(100),
            status varchar(32) NOT NULL DEFAULT 'ACTIVE',
            is_favorite boolean NOT NULL DEFAULT false,
            context_state jsonb NOT NULL DEFAULT '{}'::jsonb,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.messages (
            id uuid PRIMARY KEY,
            conversation_id uuid NOT NULL
                REFERENCES %I.conversations(id) ON DELETE CASCADE,
            role varchar(32) NOT NULL CHECK (role IN ('user', 'assistant', 'system', 'tool')),
            message text NOT NULL,
            metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
            created_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.analyses (
            id uuid PRIMARY KEY,
            conversation_id uuid NOT NULL
                REFERENCES %I.conversations(id) ON DELETE CASCADE,
            source_message_id uuid REFERENCES %I.messages(id) ON DELETE SET NULL,
            company_id integer,
            environment_id uuid,
            domain_code varchar(100),
            module_id integer REFERENCES public.protheus_modules_master(id),
            intent_code varchar(100),
            dataset_type varchar(64),
            analysis_version integer NOT NULL DEFAULT 1 CHECK (analysis_version > 0),
            schema_json jsonb,
            metrics_json jsonb,
            insights_json jsonb,
            validation_json jsonb,
            presentation_json jsonb,
            quality_score numeric(10,2),
            status varchar(32) NOT NULL DEFAULT 'COMPLETED',
            error_json jsonb,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema, v_schema, v_schema);

    EXECUTE format($ddl$
        CREATE TABLE IF NOT EXISTS %I.dashboards (
            id uuid PRIMARY KEY,
            conversation_id uuid NOT NULL
                REFERENCES %I.conversations(id) ON DELETE CASCADE,
            analysis_id uuid NOT NULL
                REFERENCES %I.analyses(id) ON DELETE RESTRICT,
            title varchar(255),
            dashboard_type varchar(64),
            dashboard_json jsonb NOT NULL,
            is_favorite boolean NOT NULL DEFAULT false,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $ddl$, v_schema, v_schema, v_schema);

    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.dictionary_tables(module_id, active)',
                   'idx_dictionary_tables_module_active', v_schema);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.business_rules(module_id, active)',
                   'idx_business_rules_module_active', v_schema);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.messages(conversation_id, created_at)',
                   'idx_messages_conversation_created', v_schema);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.analyses(conversation_id, created_at)',
                   'idx_analyses_conversation_created', v_schema);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.dashboards(analysis_id)',
                   'idx_dashboards_analysis', v_schema);

    UPDATE public.tenant
       SET provisioned_at = coalesce(provisioned_at, now()),
           updated_at = now()
     WHERE tenant_code = p_tenant_code;

    RETURN v_schema;
END
$factory$;

REVOKE ALL ON FUNCTION public.provision_tenant_schema(varchar) FROM PUBLIC;

COMMENT ON FUNCTION public.provision_tenant_schema(varchar) IS
'Cria somente estruturas de metadados/configuração no schema físico do tenant; não replica dados transacionais do Protheus.';

COMMIT;
